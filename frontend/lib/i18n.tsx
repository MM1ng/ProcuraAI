type TranslationKey = keyof typeof dictionaries.en;

type LanguageContextValue = {
  language: LanguageCode;
  setLanguage: (language: LanguageCode) => void;
  t: (key: TranslationKey, replacements?: Record<string, string | number>) => string;
  translateCategory: (category: string) => string;
  translateStatus: (status: string) => string;
};

const LanguageContext = createContext<LanguageContextValue | null>(null);

function interpolate(value: string, replacements?: Record<string, string | number>) {
  if (!replacements) return value;
  return Object.entries(replacements).reduce(
    (text, [key, replacement]) => text.replaceAll(`{${key}}`, String(replacement)),
    value
  );
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<LanguageCode>("en");

  useEffect(() => {
    const stored = window.localStorage.getItem("language");
    if (stored === "en" || stored === "zh") {
      setLanguageState(stored);
    } else if (stored === "fr") {
      // Migrate legacy FR users to ZH
      setLanguageState("zh");
      window.localStorage.setItem("language", "zh");
    }
  }, []);

  const value = useMemo<LanguageContextValue>(() => {
    function setLanguage(nextLanguage: LanguageCode) {
      setLanguageState(nextLanguage);
      window.localStorage.setItem("language", nextLanguage);
    }

    function t(key: TranslationKey, replacements?: Record<string, string | number>) {
      // Fallback chain: current language → English → key itself
      const dict = dictionaries[language];
      const value = dict?.[key] || dictionaries.en[key] || key;
      return interpolate(value, replacements);
    }

    function translateCategory(category: string) {
      const key = `category.${category}` as TranslationKey;
      return dictionaries[language]?.[key] || dictionaries.en[key] || category;
    }

    function translateStatus(status: string) {
      const key = `status.${status}` as TranslationKey;
      return dictionaries[language]?.[key] || dictionaries.en[key] || status;
    }

    return { language, setLanguage, t, translateCategory, translateStatus };
  }, [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error("useLanguage must be used within LanguageProvider");
  }
  return context;
}
