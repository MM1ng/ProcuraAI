"""Read-only independent recount/source/archival fidelity check, no app imports."""
import ast
import hashlib
import json
from pathlib import Path
import sys
import xml.etree.ElementTree as ET

root = Path(sys.argv[1]).resolve()
public = root / "source/docs/audits/batch-3a1/revalidation-20261021"
source = root / "source"
original = root.parent / "work/ProcuraAI"
results = {"phases": [], "historical_results_replaced": False}
for phase, count in [("green", 26), ("regression", 77)]:
    xml_path = root / "attempt-04/runtime" / phase / (phase + ".xml")
    xml = ET.parse(xml_path).getroot()
    cases = list(xml.iter("testcase"))
    names = [c.attrib["classname"] + "::" + c.attrib["name"] for c in cases]
    states = {key: sum(c.find(key) is not None for c in cases) for key in ["failure", "error", "skipped"]}
    assert len(cases) == count and len(set(names)) == count and not any(states.values())
    for suite in xml.iter("testsuite"):
        items = list(suite.iter("testcase"))
        assert int(suite.attrib["tests"]) == len(items)
        assert all(int(suite.attrib[key]) == 0 for key in ["failures", "errors", "skipped"])
    functions = {}
    for name in ["test_debug_access_batch3a1", "test_transaction_snapshot_batch1", "test_caller_ownership_batch2"]:
        tree = ast.parse((source / "backend/tests" / (name + ".py")).read_text(encoding="utf-8"))
        functions[name] = {n.name for n in ast.walk(tree) if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef))}
    for c in cases:
        assert c.attrib["name"].split("[")[0] in functions[c.attrib["classname"].split(".")[-1]]
    historic = ET.parse(root.parent / ".codex-batch3a1-20261010" / (phase + ".xml")).getroot()
    historic_names = [c.attrib["classname"] + "::" + c.attrib["name"] for c in historic.iter("testcase")]
    assert names == historic_names
    before = json.loads((root / "attempt-04/raw" / (phase + "-source-before.json")).read_text())
    after = json.loads((root / "attempt-04/raw" / (phase + "-source-after.json")).read_text())
    assert before["tracked_sha256"] == after["tracked_sha256"] and not before["status"] and not after["status"]
    data_before = json.loads((root / "attempt-04/raw" / (phase + "-protected-before.json")).read_text())
    data_after = json.loads((root / "attempt-04/raw" / (phase + "-protected-after.json")).read_text())
    assert data_before["files"] == data_after["files"]
    for name, value in data_after["files"].items():
        assert hashlib.sha256((original / name).read_bytes()).hexdigest().upper() == value["sha256"]
    results["phases"].append({"phase": phase, "total": count, "pass": count,
        "fail": 0, "error": 0, "skip": 0, "duplicate_names": 0,
        "suite_attributes_match": True, "names_match_historical_selection": True,
        "source_test_functions_exist": True, "tracked_files_unchanged": len(before["tracked_sha256"]),
        "protected_files_unchanged": len(data_before["files"])})

results["scope"] = "Independent read-only XML/AST/hash check, not another test execution; parameter identities checked against archived XML, not regenerated by pytest collection."
print(json.dumps(results, indent=2))
